def get_icon(name: str, color: str = "#8E8E93", size: int = 18) -> QIcon:
    """Generate a sharp QIcon from outline SVG string with desired stroke color."""
    template = SVG_ICONS.get(name, SVG_ICONS["dashboard"])
    svg_data = template.replace("{color}", color).strip()

    renderer = QSvgRenderer(QByteArray(svg_data.encode("utf-8")))
    pixmap = QPixmap(size, size)
    pixmap.fill("transparent")

    painter = QPainter(pixmap)
    renderer.render(painter)
    painter.end()

    return QIcon(pixmap)

